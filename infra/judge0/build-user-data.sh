#!/usr/bin/env bash
# Build EC2 user data that installs Judge0 unattended on a fresh Ubuntu 22.04 instance.
#
#   bash infra/judge0/build-user-data.sh [BIND_IP] > judge0-user-data.sh
#
# BIND_IP defaults to 127.0.0.1: Judge0 is reachable only through an SSM/SSH tunnel.
# For a backend inside the VPC, pass the instance's private IP instead.
#
# Boot 1 switches the kernel to cgroup v1 and reboots; a one-shot systemd unit then
# installs Judge0 on boot 2. Progress: /var/log/judge0-setup.log on the instance.
set -euo pipefail
BIND_IP="${1:-127.0.0.1}"
DIR="$(cd "$(dirname "$0")" && pwd)"
CGROUP_B64="$(base64 -w0 "$DIR/provision-cgroup.sh")"
JUDGE0_B64="$(base64 -w0 "$DIR/provision-judge0.sh")"

cat <<EOF
#!/bin/bash
# Generated by infra/judge0/build-user-data.sh — do not edit; regenerate instead.
set -euo pipefail
exec >> /var/log/judge0-setup.log 2>&1
echo "[judge0-setup] stage 1 starting \$(date -u)"
mkdir -p /opt/judge0-setup
echo "$CGROUP_B64" | base64 -d > /opt/judge0-setup/provision-cgroup.sh
echo "$JUDGE0_B64" | base64 -d > /opt/judge0-setup/provision-judge0.sh
chmod 700 /opt/judge0-setup/provision-cgroup.sh /opt/judge0-setup/provision-judge0.sh
cat > /etc/systemd/system/judge0-setup.service <<'UNIT'
[Unit]
Description=Install Judge0 (stage 2, after the cgroup v1 reboot)
After=network-online.target
Wants=network-online.target
ConditionPathExists=!/opt/judge0-setup/.done

[Service]
Type=oneshot
Environment=JUDGE0_BIND_IP=$BIND_IP
ExecStart=/bin/bash -c '/opt/judge0-setup/provision-judge0.sh && touch /opt/judge0-setup/.done'
StandardOutput=append:/var/log/judge0-setup.log
StandardError=append:/var/log/judge0-setup.log
TimeoutStartSec=1800

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable judge0-setup.service
bash /opt/judge0-setup/provision-cgroup.sh
echo "[judge0-setup] rebooting into cgroup v1"
reboot
EOF
