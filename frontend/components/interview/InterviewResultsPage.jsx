'use client';

import React, { useCallback, useEffect, useRef, useState } from 'react';
import Link from 'next/link';
import { AlertCircle, AlertTriangle, ArrowLeft, Loader2, PlayCircle, RotateCcw } from 'lucide-react';
import { extractErrorMessage, generateInterviewReport, getInterview, getInterviewReport } from '@/services/api';
import AnswerFeedback, { ScoreBar } from '@/components/interview/AnswerFeedback';
import {
  DIMENSION_LABELS,
  SCORE_DISCLAIMER,
  STATUS_META,
  categoryLabel,
  difficultyLabel,
  formatDateTime,
  modeLabel,
  scoreBand,
  typeLabel,
} from '@/components/interview/interviewConstants';

function ListSection({ title, items, ordered = false }) {
  if (!items?.length) return null;
  const ListTag = ordered ? 'ol' : 'ul';
  return (
    <div>
      <h3 className="text-sm font-semibold text-slate-900">{title}</h3>
      <ListTag className={`mt-2 space-y-1.5 pl-5 text-sm leading-6 text-slate-700 ${ordered ? 'list-decimal' : 'list-disc'}`}>
        {items.map((item) => (
          <li key={item}>{item}</li>
        ))}
      </ListTag>
    </div>
  );
}

export default function InterviewResultsPage({ interviewId }) {
  const [interview, setInterview] = useState(null);
  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [notFound, setNotFound] = useState(false);
  const [noReport, setNoReport] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [generateError, setGenerateError] = useState('');
  const autoGenerated = useRef(false);

  const generate = useCallback(async () => {
    setGenerating(true);
    setGenerateError('');
    try {
      setReport(await generateInterviewReport(interviewId));
    } catch (err) {
      setGenerateError(extractErrorMessage(err));
    }
    try {
      setInterview(await getInterview(interviewId));
    } catch {
      // per-question detail stays as previously loaded
    }
    setGenerating(false);
  }, [interviewId]);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const detail = await getInterview(interviewId);
        if (cancelled) return;
        setInterview(detail);
        if (detail.status === 'IN_PROGRESS') return;
        try {
          const stored = await getInterviewReport(interviewId);
          if (!cancelled) setReport(stored);
        } catch (err) {
          if (cancelled) return;
          if (err?.response?.status === 404) setNoReport(true);
          else setError(extractErrorMessage(err));
        }
      } catch (err) {
        if (cancelled) return;
        if (err?.response?.status === 404) setNotFound(true);
        else setError(extractErrorMessage(err));
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [interviewId]);

  // A freshly ended interview has a PENDING report: generate it once automatically.
  useEffect(() => {
    if (report?.status === 'PENDING' && report.can_retry && !autoGenerated.current) {
      autoGenerated.current = true;
      generate();
    }
  }, [generate, report]);

  if (loading) {
    return (
      <div className="flex min-h-[50vh] items-center justify-center" role="status">
        <Loader2 className="mr-2 h-5 w-5 animate-spin text-brand-500" aria-hidden="true" />
        <span className="text-sm text-slate-500">Loading your results...</span>
      </div>
    );
  }

  if (notFound || error) {
    return (
      <div className="surface-card mx-auto max-w-xl text-center" role="alert">
        <AlertCircle className="mx-auto h-8 w-8 text-red-600" aria-hidden="true" />
        <h1 className="mt-3 text-lg font-semibold">{notFound ? 'Interview not found' : 'Unable to load results'}</h1>
        <p className="mt-1 text-sm text-slate-500">{notFound ? 'It may belong to another account.' : error}</p>
        <Link href="/dashboard/interview/history" className="btn-outline mt-4">
          Interview history
        </Link>
      </div>
    );
  }

  if (!interview) return null;

  if (interview.status === 'IN_PROGRESS') {
    return (
      <div className="surface-card mx-auto max-w-xl text-center">
        <h1 className="text-lg font-semibold">This interview is still in progress</h1>
        <p className="mt-1 text-sm text-slate-500">The final report becomes available once the interview ends.</p>
        <Link href={`/dashboard/interview/${interviewId}`} className="btn-primary mt-4">
          <PlayCircle className="h-4 w-4" aria-hidden="true" />
          Resume interview
        </Link>
      </div>
    );
  }

  const meta = STATUS_META[interview.status] || STATUS_META.COMPLETED;
  const aggregates = report?.aggregates;
  const narrative = report?.narrative;
  const overall = report?.overall_score;
  const band = scoreBand(overall);
  const dimensions = Object.entries(aggregates?.dimension_scores || {}).filter(([, value]) => value !== null && value !== undefined);
  const categories = Object.entries(aggregates?.category_scores || {}).filter(([, value]) => value !== null && value !== undefined);
  const isGenerating = generating || (report?.status === 'PENDING' && report?.can_retry && !generateError);

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
        <div className="min-w-0">
          <Link href="/dashboard/interview/history" className="inline-flex items-center gap-1 text-sm font-medium text-brand-500 hover:underline">
            <ArrowLeft className="h-4 w-4" aria-hidden="true" />
            Interview history
          </Link>
          <h1 className="page-title mt-2 truncate">{interview.target_role}</h1>
          <p className="mt-1 text-sm text-slate-500">
            {typeLabel(interview.interview_type)} · {difficultyLabel(interview.difficulty)} · {modeLabel(interview.interaction_mode)} ·{' '}
            {interview.duration_minutes} min · {formatDateTime(interview.started_at)}
          </p>
        </div>
        <span className={`inline-flex w-fit shrink-0 rounded-full border px-3 py-1 text-xs font-semibold ${meta.className}`}>{meta.label}</span>
      </div>

      {noReport ? (
        <div className="surface-card text-center">
          <h2 className="text-lg font-semibold">No report for this interview</h2>
          <p className="mt-1 text-sm text-slate-500">No answers were submitted before the interview ended.</p>
          <Link href="/dashboard/interview" className="btn-primary mt-4">
            Start a new interview
          </Link>
        </div>
      ) : (
        <>
          <section className="surface-card grid gap-6 md:grid-cols-[220px_minmax(0,1fr)]" aria-labelledby="overall-heading">
            <div>
              <h2 id="overall-heading" className="text-xs font-semibold uppercase tracking-wide text-slate-500">
                Overall score
              </h2>
              {overall !== null && overall !== undefined ? (
                <>
                  <p className="mt-1 text-5xl font-bold text-slate-900">
                    {overall}
                    <span className="text-xl font-medium text-slate-400">/100</span>
                  </p>
                  <p className={`mt-1 text-sm font-semibold ${band.className}`}>{band.label}</p>
                </>
              ) : (
                <p className="mt-2 text-sm text-slate-500">{isGenerating ? 'Calculating...' : 'Not available yet'}</p>
              )}
              {aggregates && (
                <p className="mt-3 text-xs text-slate-500">
                  {aggregates.evaluated_count} of {aggregates.answered_count} answers scored · {aggregates.question_count} questions asked
                </p>
              )}
            </div>
            <div className="space-y-4">
              {categories.length > 1 && (
                <div className="grid gap-3 sm:grid-cols-2">
                  {categories.map(([category, value]) => (
                    <ScoreBar key={category} label={`${categoryLabel(category)} performance`} value={value} />
                  ))}
                </div>
              )}
              {dimensions.length > 0 && (
                <div>
                  <h3 className="text-sm font-semibold text-slate-900">Breakdown by dimension</h3>
                  <div className="mt-3 grid gap-3 sm:grid-cols-2">
                    {dimensions.map(([key, value]) => (
                      <ScoreBar key={key} label={DIMENSION_LABELS[key] || key} value={value} />
                    ))}
                  </div>
                </div>
              )}
              <p className="text-xs leading-5 text-slate-500">
                {report?.score_scale || SCORE_DISCLAIMER}
              </p>
              {aggregates?.methodology && (
                <details className="text-xs text-slate-500">
                  <summary className="cursor-pointer font-medium text-slate-600">How the score is calculated</summary>
                  <p className="mt-1 leading-5">{aggregates.methodology}</p>
                </details>
              )}
            </div>
          </section>

          <section className="surface-card space-y-5" aria-labelledby="summary-heading">
            <h2 id="summary-heading" className="text-base font-semibold">Performance summary</h2>
            {isGenerating ? (
              <p className="flex items-center gap-2 text-sm text-slate-600" role="status">
                <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
                Generating your report. This can take a minute...
              </p>
            ) : narrative ? (
              <>
                <p className="text-sm leading-7 text-slate-700">{narrative.summary}</p>
                <div className="grid gap-5 md:grid-cols-2">
                  <ListSection title="Strengths" items={narrative.strengths} />
                  <ListSection title="Areas to improve" items={narrative.weaknesses} />
                  <ListSection title="Repeated gaps" items={narrative.repeated_gaps} />
                  <ListSection title="Improvement plan" items={narrative.improvement_plan} ordered />
                </div>
                {narrative.topics_to_revise?.length > 0 && (
                  <div>
                    <h3 className="text-sm font-semibold text-slate-900">Recommended topics to revise</h3>
                    <div className="mt-2 flex flex-wrap gap-1.5">
                      {narrative.topics_to_revise.map((topic) => (
                        <span key={topic} className="rounded-full border border-brand-200 bg-brand-50 px-2.5 py-1 text-xs font-medium text-brand-600">
                          {topic}
                        </span>
                      ))}
                    </div>
                  </div>
                )}
              </>
            ) : (
              <div className="rounded-xl border border-amber-200 bg-amber-50 p-4 text-sm text-amber-900" role="alert">
                <p className="flex items-center gap-2 font-semibold">
                  <AlertTriangle className="h-4 w-4" aria-hidden="true" />
                  The written summary couldn&apos;t be generated.
                </p>
                <p className="mt-1">
                  {generateError || 'Your answers and any available per-question feedback are saved below.'}
                </p>
                {report?.can_retry && (
                  <button type="button" onClick={generate} className="btn-outline mt-3">
                    <RotateCcw className="h-4 w-4" aria-hidden="true" />
                    Retry report
                  </button>
                )}
              </div>
            )}

            {(aggregates?.strongest?.length > 0 || aggregates?.weakest?.length > 0) && (
              <div className="grid gap-4 border-t border-slate-100 pt-4 sm:grid-cols-2">
                {[
                  ['Strongest answers', aggregates.strongest],
                  ['Weakest answers', aggregates.weakest],
                ].map(([title, refs]) =>
                  refs?.length ? (
                    <div key={title}>
                      <h3 className="text-sm font-semibold text-slate-900">{title}</h3>
                      <ul className="mt-2 space-y-1 text-sm text-slate-700">
                        {refs.map((ref) => (
                          <li key={ref.question_id} className="flex justify-between gap-2">
                            <span className="truncate">
                              Q{ref.question_order}. {ref.competency}
                            </span>
                            <span className="shrink-0 font-semibold">{ref.score}</span>
                          </li>
                        ))}
                      </ul>
                    </div>
                  ) : null
                )}
              </div>
            )}
          </section>
        </>
      )}

      <section aria-labelledby="questions-heading" className="space-y-3">
        <h2 id="questions-heading" className="text-base font-semibold">Question-by-question feedback</h2>
        {interview.questions.length === 0 ? (
          <p className="surface-card-subtle text-sm text-slate-500">No questions were asked.</p>
        ) : (
          interview.questions.map((question) => (
            <details key={question.id} className="surface-card p-4 sm:p-5" open={interview.questions.length <= 3}>
              <summary className="flex cursor-pointer items-start justify-between gap-3">
                <span className="min-w-0">
                  <span className="block text-xs font-semibold uppercase tracking-wide text-slate-500">
                    Question {question.question_order} · {categoryLabel(question.category)} · {question.competency}
                  </span>
                  <span className="mt-1 block text-sm font-medium text-slate-900">{question.question_text}</span>
                </span>
                <span className="shrink-0 text-sm font-semibold text-slate-700">
                  {!question.answer
                    ? 'Not answered'
                    : question.answer.score !== null && question.answer.score !== undefined
                      ? `${question.answer.score}/100`
                      : 'Not scored'}
                </span>
              </summary>
              {question.answer ? (
                <div className="mt-4 space-y-4">
                  <div className="surface-card-subtle">
                    <p className="text-xs font-semibold uppercase tracking-wide text-slate-500">Your answer</p>
                    <p className="mt-1.5 whitespace-pre-wrap text-sm leading-6 text-slate-700">{question.answer.answer_text}</p>
                  </div>
                  <AnswerFeedback answer={question.answer} />
                </div>
              ) : (
                <p className="mt-3 text-sm text-slate-500">This question was not answered and is not included in the score.</p>
              )}
            </details>
          ))
        )}
      </section>

      <div className="flex justify-center">
        <Link href="/dashboard/interview" className="btn-primary">
          <PlayCircle className="h-4 w-4" aria-hidden="true" />
          Start another interview
        </Link>
      </div>
    </div>
  );
}
